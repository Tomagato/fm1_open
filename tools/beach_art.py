"""Draw the palm silhouettes for the Beach 909 screen.

Original artwork, generated from the strokes below on the 120x56 logical
grid that app/beach_scene.inc paints at 2x. Run from the repository root:

    python3 tools/beach_art.py > app/beach_art.inc
"""
W, H = 120, 56
grid = [[0] * W for _ in range(H)]


def dot(x, y, r=0):
    for yy in range(int(round(y)) - r, int(round(y)) + r + 1):
        for xx in range(int(round(x)) - r, int(round(x)) + r + 1):
            if 0 <= xx < W and 0 <= yy < H:
                grid[yy][xx] = 1


def bezier(p0, p1, p2, steps=60):
    for i in range(steps + 1):
        t = i / steps
        a, b, c = (1 - t) ** 2, 2 * t * (1 - t), t * t
        yield t, a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]


def trunk(base, bend, crown, width):
    for t, x, y in bezier(base, bend, crown, 120):
        half = width * (1 - 0.55 * t) / 2
        for k in range(int(round(-half * 2)), int(round(half * 2)) + 1):
            dot(x + k / 2, y)


def frond(crown, bend, tip, leaf):
    for t, x, y in bezier(crown, bend, tip):
        dot(x, y)
        # Leaflets hang below the rib and shorten toward the tip.
        n = int(round(leaf * (1 - abs(t - 0.45) * 1.6)))
        if int(t * 60) % 2 == 0:
            for k in range(1, max(n, 0) + 1):
                dot(x, y + k)


def palm(base, bend, crown, width, size, lean):
    trunk(base, bend, crown, width)
    cx, cy = crown
    dot(cx, cy, 1)
    dot(cx - 1, cy + 2)
    dot(cx + 1, cy + 2)  # coconuts
    s = size
    for bx, by, tx, ty, leaf in (
        (-0.55, -0.55, -1.10, 0.10, 3), (-0.75, -0.10, -1.00, 0.70, 3),
        (-0.20, -0.80, -0.55, -0.55, 2), (0.25, -0.85, 0.60, -0.50, 2),
        (0.60, -0.55, 1.15, 0.15, 3), (0.75, -0.05, 0.95, 0.75, 3),
        (0.05, -0.30, 0.12, -0.68, 1),
    ):
        frond(crown, (cx + (bx + lean) * s, cy + by * s), (cx + (tx + lean) * s, cy + ty * s), leaf)


palm((13, 52), (15, 30), (27, 14), 3.2, 17, 0.05)
palm((110, 58), (109, 40), (100, 25), 2.6, 12, -0.08)

print('/* SPDX-License-Identifier: GPL-3.0-only WITH GPL-3.0-linking-exception */')
print('/* Generated by tools/beach_art.py: palm silhouettes, 120x56, bit 0 = left pixel. */')
print('static const uint8_t beach_palms[%d][%d] = {' % (H, W // 8))
for row in grid:
    data = [sum(row[b * 8 + i] << i for i in range(8)) for b in range(W // 8)]
    print('    {' + ','.join('0x%02x' % v for v in data) + '},')
print('};')
